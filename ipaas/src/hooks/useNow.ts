import { useEffect, useState } from 'react';

/**
 * The current time, refreshed every `intervalMs` while `enabled`, so a "14 min
 * so far" text keeps counting without the data behind it changing. While not
 * enabled it stops ticking and keeps the last value.
 */
export function useNow(intervalMs: number, enabled = true): number {
  const [now, setNow] = useState(() => Date.now());
  useEffect(() => {
    if (!enabled) return;
    setNow(Date.now());
    const timer = window.setInterval(() => setNow(Date.now()), intervalMs);
    return () => window.clearInterval(timer);
  }, [intervalMs, enabled]);
  return now;
}
