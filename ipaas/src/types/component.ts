export type DisplayType = 'ballerinaService' | 'scheduledTask' | 'manualTrigger' | 'webhook' | 'miApiService' | 'miCronjob' | 'miJob' | 'miWebhook' | 'miEventHandler' | 'ballerinaEventHandler';

export interface CreateComponentInput {
  displayName: string;
  name: string;
  description: string;
  orgHandler: string;
  projectId: string;
  displayType: DisplayType;
  /**
   * Optional subtype that further classifies the component beyond its
   * `displayType`. Used to flag File Integration (`'ballerinaFileIntegration'`,
   * `'miFileIntegration'`), AI Agent, MCP, Tailscale, etc., where the build
   * runtime is shared with another type (e.g. `ballerinaService`) but the
   * functional category differs.
   */
  componentSubType?: string;
  srcGitRepoUrl?: string;
  repositoryBranch?: string;
  repositorySubPath?: string;
  isPublicRepo?: boolean;
  enableAutoDeploy?: boolean;
  isPrebuilt?: boolean;
  /**
   * GitHub App installation that grants access to srcGitRepoUrl (cloud
   * private-repo mode). When set, the cloud BFF persists the source binding
   * and provisions per-build clone secrets; other variants ignore it.
   */
  gitHubAppInstallationId?: string;
}

