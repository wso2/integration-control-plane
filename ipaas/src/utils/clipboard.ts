/** Copies through a hidden text area, for pages without the async clipboard. True when the browser reports it copied. */
function copyBySelection(value: string): boolean {
  const area = document.createElement('textarea');
  area.value = value;
  area.setAttribute('readonly', '');
  area.style.position = 'fixed';
  area.style.opacity = '0';
  document.body.appendChild(area);
  area.select();
  try {
    return document.execCommand('copy');
  } catch {
    return false;
  } finally {
    area.remove();
  }
}

/**
 * Writes `value` to the clipboard. The async clipboard exists only on https and localhost, so a plain-http host
 * (the local stack) falls back to a hidden selection. Resolves true only when the copy happened.
 */
export async function copyToClipboard(value: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(value);
      return true;
    }
    return copyBySelection(value);
  } catch {
    return false;
  }
}
